def test_no_british_spelling_in_tracked_text():
    bad, _ = scan(tracked_text_files())
    msg = ("house spelling is American (drift: every British word is a template the next edit copies). "
           "Quoting someone else's text? put 'spelling: allow <word>' on that line "
           "(in Markdown, inside <!-- -->). Never respell a field name or key the spec defines.\n")
    assert bad == [], msg + "\n".join(bad)


def test_every_pragma_still_has_its_reason():
    _, stale = scan(tracked_text_files())
    assert stale == [], "\n".join(stale)


def test_the_scan_covers_the_package_the_specs_js_and_slicer():
    """A file filter that matched nothing would pass the tests above trivially."""
    names = set(tracked_text_files())
    assert len(names) > 100
    for must in ("src/duckn/models.py", "README.md", "CHANGELOG.md", "pyproject.toml",
                 "docs/duckn-spec.md", "docs/segmentation-ext-spec.md", "tests/test_docs.py",
                 "js/duckn-reader/src/index.js", "js/duckn-spatial/src/index.js",
                 "js/duckn-cornerstone/src/index.ts", "js/duckn-cornerstone/scripts/sync-spatial.mjs",
                 "slicer/SlicerDuckn/SlicerDucknIO/SlicerDucknIO.py"):
        assert must in names, must
    assert SELF not in names


def test_without_git_the_scan_fails_rather_than_passing_empty(tmp_path):
    with pytest.raises(AssertionError, match="git checkout"):
        tracked_text_files(tmp_path)


