def test_a_pragma_allows_only_its_word_on_its_line(tmp_path):
    (tmp_path / "x.py").write_text("c = sw.centre  # spelling: allow centre\n"
                                   "colour = 1  # spelling: allow centre\n"
                                   "ok = 2  # spelling: allow grey\n")
    (tmp_path / "x.md").write_text('DICOM calls it "Colour" <!-- spelling: allow colour -->\n')
    bad, stale = scan(["x.py", "x.md"], root=tmp_path)
    assert bad == ["x.py:2: 'colour' -> 'color'"]
    assert len(stale) == 2                                     # line 2's centre and line 3's grey are not there
