"""The house spelling is American, in every tracked text file (2026-09-22).

Ported from haversack (commit 514332c), where it was made critical after new scripts picked up
"centre" from a sibling repository's API. The reason is DRIFT: every British word already in a
file is a template the next edit copies, so a clean tree has to be held clean by a test, not by
care. duckn's specs also sit beside DICOM, NIfTI and NRRD, which are American ("Window Center"),
so a British word in a spec reads as a second convention.

The detector is an explicit list of British forms, never a suffix rule: "-ise" would flag advise,
exercise, precise and noise, and "-our" would flag four and contour. Identifiers are split before
matching (``centre_err``, ``colourMap``, ``NormaliseHU``), so a local name drifts no more quietly
than a comment does. Python, Markdown, JavaScript and TypeScript are all scanned: ``js/`` and
``slicer/`` are where a sibling project's spelling arrives first.

What is never respelled: a name the spec defines or a file carries - a field, an extension, an
enum value, a DICOM keyword, an NRRD field, a Slicer ``Segment*`` key. Those are wire formats.
None of duckn's is British today; if one ever is, it goes in ``GLOBAL_OK`` with its reason.

Exceptions have to be named where they are and have to stay true:

- A line that must quote someone else's spelling (an external standard's text, a paper's title,
  a third-party attribute) says so on that line: ``spelling: allow <word>``. In Markdown, put it
  in an HTML comment so it does not render: ``<!-- spelling: allow colour -->``. It allows that
  word on that line only, and a pragma whose word is no longer on its line fails the test - an
  exception may not outlive its reason.
- This file lists the British forms it looks for, so it is not scanned; the detector tests below
  are what hold it to its job.
"""

